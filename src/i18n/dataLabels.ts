/** t() imzası (LanguageContext.t ile aynı). */
type Translate = (key: string) => string;

/**
 * t() eksik anahtarda HAM ANAHTARI döndürür (bilinen takip: "t() fallback ham
 * anahtar döndürür"). Bu sarmalayıcı, anahtar sözlükte yoksa kullanıcıya ham
 * key sızdırmak yerine KAYNAK LİTERAL'e (İngilizce) düşer — böylece eksik bir
 * çeviri en kötü ihtimalle İngilizce görünür, "dkpi.foo.label" gibi değil.
 */
function resolve(t: Translate, key: string, fallback: string): string {
  const out = t(key);
  return out === key ? fallback : out;
}

// -- birim literali -> anahtar sonu. '%' ve '/5' evrensel; eşlenmez (aynen döner).
const UNIT_SLUG: Record<string, string> = {
  'units/day': 'unitsPerDay',
  days: 'days',
  'kWh/unit': 'kwhPerUnit',
  value: 'value',
  'kg CO2/unit': 'kgco2PerUnit',
  units: 'units',
};

// -- node metrik etiketi (serbest metin) -> anahtar sonu.
const METRIC_SLUG: Record<string, string> = {
  'Lead Time': 'leadTime',
  Reliability: 'reliability',
  OEE: 'oee',
  Throughput: 'throughput',
  'Delivery Accuracy': 'deliveryAccuracy',
  'Avg Transit Time': 'avgTransitTime',
  Satisfaction: 'satisfaction',
  'Weekly Demand': 'weeklyDemand',
};

/** KPI kart başlığı/etiketi — kpi.id kararlı anahtar. */
export function tKpiLabel(t: Translate, kpi: Pick<KpiData, 'id' | 'label'>): string {
  return resolve(t, `dkpi.${kpi.id}`, kpi.label);
}

/** KPI küme/kategori rozeti (delivery/cost/stock/resource/energy). */
export function tCluster(t: Translate, cluster: KpiCluster): string {
  return resolve(t, `dcluster.${cluster}`, cluster);
}

/** Birim (%, units/day, days, ...). Bilinmeyen birim aynen döner. */
export function tUnit(t: Translate, unit: string | undefined): string {
  if (!unit) return '';
  const slug = UNIT_SLUG[unit];
  if (!slug) return unit;
  return resolve(t, `dunit.${slug}`, unit);
}

/** Value Chain düğüm adı — node.id kararlı anahtar. */
export function tNodeName(t: Translate, node: Pick<DigitalTwinNode, 'id' | 'name'>): string {
  return resolve(t, `dnode.${node.id}`, node.name);
}

/** Value Chain düğüm tipi (supplier/manufacturer/logistics/customer). */
export function tNodeType(t: Translate, type: DigitalTwinNode['type']): string {
  return resolve(t, `dtype.${type}`, type);
}

/** Value Chain düğüm metrik etiketi (serbest metin). Bilinmeyen aynen döner. */
export function tMetricLabel(t: Translate, label: string): string {
  const slug = METRIC_SLUG[label];
  if (!slug) return label;
  return resolve(t, `dmetric.${slug}`, label);
}

/**
 * ── ALARM METNİ (veri-kaynaklı) ──────────────────────────────────────────────
 * "Son Uyarılar" bölümü (Dashboard widget + Alert Center) alarmlarını
 * `data/alerts.ts`'ten okur; başlık/metin İngilizce LİTERAL taşıyordu ve dil
 * değişince İngilizce kalıyordu (KpiCard/ValueChainDT ile aynı kök neden).
 * Alarm KARARLI `id` taşır → buradaki `dalert.<id>.title|msg` karşılığına
 * eşlenir. ÖLÇÜLEN DEĞERLER KORUNUR: sayılar, yüzdeler, parça No/tanımı ve ham
 * ERP kategori değerleri (QUARANTAINE, DEROGATION ACCEPTEE, Supply, Etiquette,
 * Quantité, Visuel) çevirilerde AYNEN bırakılır; yalnız betimleyici sözcükler
 * dile bağlanır. `alert.dataSource` provenans dizesi (KpiCard.dataSource ile
 * aynı sözleşme) çevrilmez — kaynak dilde kalır. */
export function tAlertTitle(t: Translate, alert: Pick<Alert, 'id' | 'title'>): string {
  return resolve(t, `dalert.${alert.id}.title`, alert.title);
}

export function tAlertMessage(t: Translate, alert: Pick<Alert, 'id' | 'message'>): string {
  return resolve(t, `dalert.${alert.id}.msg`, alert.message);
}

/** Göreli zaman ("5 dk önce"). Anahtar eksikse İngilizce şablona düşer. */
export function tTimeAgo(t: Translate, date: Date, now: Date = new Date()): string {
  const diff = Math.max(0, now.getTime() - date.getTime());
  const minutes = Math.floor(diff / 60000);
  const hours = Math.floor(minutes / 60);
  const days = Math.floor(hours / 24);
  if (minutes < 60) return resolve(t, 'dalert.ago.min', '{n}m ago').replace('{n}', String(minutes));
  if (hours < 24) return resolve(t, 'dalert.ago.hour', '{n}h ago').replace('{n}', String(hours));
  return resolve(t, 'dalert.ago.day', '{n}d ago').replace('{n}', String(days));
}

/** Simülasyon ürün-ağacı varlık tipi (FinishedGood/SubAssembly/Component). */
export function tEntityType(t: Translate, type: string): string {
  return resolve(t, `vcsim.entity.${type}`, type);
}

